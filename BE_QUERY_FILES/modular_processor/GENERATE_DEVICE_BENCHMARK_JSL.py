"""
GENERATE_DEVICE_BENCHMARK_JSL.py
--------------------------------
Generate an ad hoc JSL script that visualizes device benchmark trends from a
fixed CSV source (CURRENT_BENCHMARK.csv).

Output JSL requirements implemented:
- Charts: SMP_RATE, BEEP_RATE, SAMPLE_SIZE
- BY group: LAYER (8M5CL and 8M6CL)
- Legend: DEVICE with JMP Vibrant color theme
- Spline fits by DEVICE, with spline controls hidden (Report(0))
- X-axis: weekly interval with 4-week tick increments
- RATE y-axis limits: -0.01 to 0.75
"""

from __future__ import annotations

from datetime import datetime
from pathlib import Path

import pandas as pd

import sys

sys.path.insert(0, str(Path(__file__).resolve().parents[1]))

from pipeline_config import PIPELINE_PATHS, ensure_pipeline_dirs


INPUT_CSV = PIPELINE_PATHS.benchmark_dir / "CURRENT_BENCHMARK.csv"
OUTPUT_JSL = PIPELINE_PATHS.benchmark_dir / "DEVICE_BENCHMARK_PLOT.jsl"

REQUIRED_COLUMNS = {
    "PERIOD_END",
    "LAYER",
    "DEVICE",
    "SMP_RATE",
    "BEEP_RATE",
    "SAMPLE_SIZE",
}

RATE_MIN = -0.01
RATE_MAX = 0.75
RATE_INC = 0.1
SPLINE_SMOOTH = 0.1


def resolve_input_csv(preferred_input_csv: Path) -> Path:
    if preferred_input_csv.exists():
        return preferred_input_csv

    benchmark_dir = PIPELINE_PATHS.benchmark_dir
    pattern = "*_8M5CL_8M6CL_202606_FLEET_BENCHMARK_ELWC_7DAY.csv"
    candidates = sorted(benchmark_dir.glob(pattern))
    if not candidates:
        raise FileNotFoundError(
            "Input benchmark CSV not found. Missing CURRENT_BENCHMARK.csv and no dated benchmark files found."
        )
    return candidates[-1]


def _build_bivariate_block(
    y_col: str,
    y_scale_dispatch: str,
) -> str:
    return f"""\
\tBivariate(
\t\tY( :{y_col} ),
\t\tX( :PERIOD_END ),
		By( :LAYER ),
		GroupBy( :DEVICE ),
		Fit Spline( {SPLINE_SMOOTH}, Standardized, {{Report( 0 ), Line Width( 0.1 )}} ),
\t\tSendToReport(
\t\t\tDispatch(
\t\t\t\t{{}},
\t\t\t\t\"PERIOD_END\",
\t\t\t\tScaleBox,
				{{Interval( \"Week\" ), Inc( 4 ), Minor Ticks( 0 ), Label Row( {{Label Orientation( \"Angled\" ), Show Major Grid( 1 ), Show Minor Grid( 1 )}} )}}
\t\t\t),
{y_scale_dispatch}
\t\t\tDispatch(
\t\t\t\t{{}},
\t\t\t\t\"Bivar Plot\",
\t\t\t\tFrameBox,
\t\t\t\t{{Frame Size( 500, 330 ), Row Legend(
\t\t\t\t\t:DEVICE,
\t\t\t\t\tColor( 1 ),
\t\t\t\t\tColor Theme( \"JMP Vibrant\"(1) ),
\t\t\t\t\tMarker( 1 ),
\t\t\t\t\tMarker Theme( \"Standard\" ),
\t\t\t\t\tContinuous Scale( 0 ),
\t\t\t\t\tReverse Scale( 0 ),
\t\t\t\t\tExcluded Rows( 0 )
\t\t\t\t)}}
\t\t\t)
\t\t)
\t)"""


def generate_jsl(input_csv: Path, output_jsl: Path) -> Path:
    ensure_pipeline_dirs()

    resolved_input_csv = resolve_input_csv(input_csv)

    df = pd.read_csv(resolved_input_csv)
    missing = sorted(REQUIRED_COLUMNS.difference(df.columns))
    if missing:
        raise ValueError(f"Missing required columns in {resolved_input_csv.name}: {missing}")

    df["PERIOD_END"] = pd.to_datetime(df["PERIOD_END"], errors="coerce")
    if df["PERIOD_END"].isna().all():
        raise ValueError("PERIOD_END could not be parsed to datetime.")

    df = df[df["PERIOD_END"].notna()].copy()
    devices = sorted(str(v).strip() for v in df["DEVICE"].dropna().unique() if str(v).strip())
    if not devices:
        raise ValueError("No DEVICE values found in benchmark CSV.")

    smp_y_dispatch = (
        "\t\t\tDispatch(\n"
        "\t\t\t\t{},\n"
        "\t\t\t\t\"SMP_RATE\",\n"
        "\t\t\t\tScaleBox,\n"
        f"\t\t\t\t{{Min( {RATE_MIN} ), Max( {RATE_MAX} ), Inc( {RATE_INC} ), Minor Ticks( 0 ), Label Row( {{Show Major Grid( 1 ), Show Minor Grid( 1 )}} )}}\n"
        "\t\t\t),"
    )
    beep_y_dispatch = (
        "\t\t\tDispatch(\n"
        "\t\t\t\t{},\n"
        "\t\t\t\t\"BEEP_RATE\",\n"
        "\t\t\t\tScaleBox,\n"
        f"\t\t\t\t{{Min( {RATE_MIN} ), Max( {RATE_MAX} ), Inc( {RATE_INC} ), Minor Ticks( 0 ), Label Row( {{Show Major Grid( 1 ), Show Minor Grid( 1 )}} )}}\n"
        "\t\t\t),"
    )
    sample_size_y_dispatch = (
        "\t\t\tDispatch(\n"
        "\t\t\t\t{},\n"
        "\t\t\t\t\"SAMPLE_SIZE\",\n"
        "\t\t\t\tScaleBox,\n"
        "\t\t\t\t{Label Row( {Show Major Grid( 1 ), Show Minor Grid( 1 )} )}\n"
        "\t\t\t),"
    )

    smp_block = _build_bivariate_block(
        y_col="SMP_RATE",
        y_scale_dispatch=smp_y_dispatch,
    )
    beep_block = _build_bivariate_block(
        y_col="BEEP_RATE",
        y_scale_dispatch=beep_y_dispatch,
    )
    sample_size_block = _build_bivariate_block(
        y_col="SAMPLE_SIZE",
        y_scale_dispatch=sample_size_y_dispatch,
    )

    generated_ts = datetime.now().strftime("%Y-%m-%d %H:%M:%S")
    jsl = f"""// Auto-generated by GENERATE_DEVICE_BENCHMARK_JSL.py on {generated_ts}
// Source CSV: {resolved_input_csv.as_posix()}

Names Default To Here( 1 );

dt_benchmark = Open( "{resolved_input_csv.as_posix()}", Invisible );

fg = dt_benchmark << Fit Group(
{smp_block},
{beep_block},
{sample_size_block},
	<<{{Arrange in Rows( 3 )}}
);

reports = fg << Report;
If( !Is List( reports ),
	reports = {{reports}}
);

For Each( {{rpt}}, reports,
	Try( rpt[BorderBox(3)] << Visibility( "Collapse" ) );
	Try( rpt[BorderBox(4)] << Visibility( "Collapse" ) );
);
"""

    output_jsl.parent.mkdir(parents=True, exist_ok=True)
    output_jsl.write_text(jsl, encoding="utf-8")
    return output_jsl


def main() -> None:
    out_path = generate_jsl(INPUT_CSV, OUTPUT_JSL)
    print("[DONE] Device benchmark JSL generated:")
    print(f"   {out_path}")


if __name__ == "__main__":
    main()
